import { useEffect, useRef, useState } from "react";
import { Icon } from "../icons.jsx";
import { t } from "../i18n.js";
import { initialsOf } from "../ui.jsx";

/**
 * The chat widget with the current appearance settings. Without `onSend` it's a still preview;
 * with it, it's a working chat (onboarding uses it to talk to the new agent).
 * `messages`: [{ role: "visitor" | "ai" | "error", text }].
 */
export function WidgetPreview({ accent, title, agentName, welcome, branding, handoff, suggestions = [], logo, messages = [], typing = false, onSend, height = 460 }) {
  const [text, setText] = useState("");
  const body = useRef(null);
  useEffect(() => {
    if (body.current) body.current.scrollTop = body.current.scrollHeight;
  }, [messages.length, typing]);
  const live = Boolean(onSend);
  const send = (q) => {
    if (!q.trim() || typing) return;
    onSend(q.trim());
    setText("");
  };
  return (
    <section className="widget" style={{ "--w-accent": accent, height }} aria-label={live ? t("Chat with your agent") : t("Widget preview")}>
      <header className="w-head">
        <span className={"w-av" + (logo ? " has-logo" : "")} aria-hidden="true">
          {logo ? <img src={logo} alt="" /> : initialsOf(title)}
        </span>
        <div style={{ flex: 1, minWidth: 0 }}>
          <div className="w-title truncate">{title}</div>
          <div className="w-sub">
            <span className="gdot" aria-hidden="true" />
            <span className="truncate">{agentName} · {t("AI agent")}</span>
          </div>
        </div>
        <span className="w-btn" aria-hidden="true">
          <Icon name="minus" size={18} />
        </span>
      </header>
      <div className="w-body" ref={body} aria-live={live ? "polite" : undefined}>
        <div className="w-note">{t("Answers are generated by AI. A person can help if you need one.")}</div>
        <div className="wmsg bot">
          <div className="wb">{welcome || "…"}</div>
        </div>
        {suggestions.length > 0 && messages.length === 0 && (
          <div className="chips">
            {suggestions.map((q, i) =>
              live ? (
                <button type="button" className="chip" key={i} onClick={() => send(q)}>
                  {q}
                </button>
              ) : (
                <span className="chip" key={i}>
                  {q}
                </span>
              )
            )}
          </div>
        )}
        {messages.map((m, i) =>
          m.role === "error" ? (
            <div className="w-handoff" key={i} role="alert">
              {m.text}
            </div>
          ) : (
            <div className={"wmsg " + (m.role === "visitor" ? "me" : "bot")} key={i}>
              <div className="wb">{m.text}</div>
            </div>
          )
        )}
        {typing && (
          <div className="typing" role="status" aria-label={t("Agent is answering")}>
            <span />
            <span />
            <span />
          </div>
        )}
      </div>
      <div className="w-foot">
        <form
          className="w-input"
          onSubmit={(e) => {
            e.preventDefault();
            send(text);
          }}
        >
          <input
            disabled={!live}
            placeholder={t("Ask a question")}
            aria-label={live ? t("Message") : t("Message (preview)")}
            value={text}
            maxLength={2000}
            onChange={(e) => setText(e.target.value)}
          />
          {live ? (
            <button type="submit" className="w-send" aria-label={t("Send")} disabled={!text.trim() || typing}>
              <Icon name="send" size={16} />
            </button>
          ) : (
            <span className="w-send" aria-hidden="true">
              <Icon name="send" size={16} />
            </span>
          )}
        </form>
        <div className="w-links">
          {handoff ? (
            <span className="w-human">
              <Icon name="headset" size={13} />{t("Talk to a person")}
            </span>
          ) : (
            <span />
          )}
          {branding && <span>{t("Powered by Replybek")}</span>}
        </div>
      </div>
    </section>
  );
}

export const LOGO_TYPES = ["image/png", "image/jpeg", "image/gif", "image/webp", "image/svg+xml", "image/x-icon", "image/vnd.microsoft.icon"];

/** Reads a picked logo as a data: URL, or throws a message saying what's wrong with it. */
export function readLogo(file) {
  if (!LOGO_TYPES.includes(file.type)) return Promise.reject(new Error(t("Use a PNG, JPEG, GIF, WebP, ICO or SVG image.")));
  if (file.size > 200 * 1024) return Promise.reject(new Error(t("The logo must be smaller than 200 KB.")));
  return new Promise((done, fail) => {
    const reader = new FileReader();
    reader.onload = () => done(String(reader.result));
    reader.onerror = () => fail(new Error(t("Couldn't read that image.")));
    reader.readAsDataURL(file);
  });
}

/** The chat avatar: upload a small image or remove it (the widget then shows initials). Values are data: URLs. */
export function LogoPicker({ id, value, name, onChange, onError, disabled }) {
  const input = useRef(null);
  const pick = (file) => file && readLogo(file).then(onChange, (e) => onError(e.message));
  return (
    <div className="logo-picker">
      <span className={"logo-thumb" + (value ? " has-logo" : "")} aria-hidden="true">
        {value ? <img src={value} alt="" /> : initialsOf(name || "?")}
      </span>
      <input ref={input} id={id} type="file" accept={LOGO_TYPES.join(",")} className="sr-only" onChange={(e) => (pick(e.target.files[0]), (e.target.value = ""))} disabled={disabled} />
      <button type="button" className="btn btn-secondary btn-sm" onClick={() => input.current.click()} disabled={disabled}>
        <span className="btn-label">{value ? t("Replace") : t("Upload logo")}</span>
      </button>
      {value && (
        <button type="button" className="btn btn-ghost btn-sm" onClick={() => onChange("")} disabled={disabled}>
          <span className="btn-label">{t("Remove")}</span>
        </button>
      )}
    </div>
  );
}
